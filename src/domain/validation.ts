import type { CommitmentInput, CreateMitigationInput, FieldErrors } from '../shared/contracts';
import { isDateOnly } from './dates';
import { isIssueId, parseSameSiteUrl } from './urls';

/**
 * Server-side schema validation for every user-controlled payload.
 * The frontend mirrors these rules for convenience only; this module is authoritative.
 */

export const LIMITS = {
  title: { min: 5, max: 140 },
  customerLabel: { min: 1, max: 120 },
  evidenceExcerpt: { min: 10, max: 1000 },
  linkedIssues: { min: 1, max: 10 },
  mitigationSummary: { min: 1, max: 255 },
  mitigationDescription: { min: 1, max: 20000 },
} as const;

export type Validation<T> = { ok: true; value: T } | { ok: false; fieldErrors: FieldErrors; message: string };

// Control characters, allowing tab/newline/carriage return where multi-line text is expected.
// Matching control characters is the point of these patterns.
// eslint-disable-next-line no-control-regex
const CONTROL_SINGLE_LINE = /[\u0000-\u001F\u007F]/;
// eslint-disable-next-line no-control-regex
const CONTROL_MULTI_LINE = /[\u0000-\u0008\u000B\u000C\u000E-\u001F\u007F]/;

const charLength = (s: string) => [...s].length;

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

function text(
  value: unknown,
  label: string,
  { min, max }: { min: number; max: number },
  multiLine = false,
): { ok: true; value: string } | { ok: false; message: string } {
  if (typeof value !== 'string') return { ok: false, message: `${label} is required.` };
  const trimmed = value.trim();
  const length = charLength(trimmed);
  if (length === 0) return { ok: false, message: `${label} is required.` };
  if (length < min) return { ok: false, message: `${label} must be at least ${min} characters.` };
  if (length > max) return { ok: false, message: `${label} must be at most ${max} characters.` };
  if ((multiLine ? CONTROL_MULTI_LINE : CONTROL_SINGLE_LINE).test(trimmed)) {
    return { ok: false, message: `${label} contains unsupported characters.` };
  }
  return { ok: true, value: trimmed };
}

/** Validate the F02 create/edit payload. `siteBaseUrl` is the authoritative site URL from Jira. */
export function validateCommitmentInput(raw: unknown, siteBaseUrl: string): Validation<CommitmentInput> {
  if (!isRecord(raw)) {
    return { ok: false, fieldErrors: {}, message: 'The commitment details are missing.' };
  }
  const fieldErrors: FieldErrors = {};

  const title = text(raw.title, 'Title', LIMITS.title);
  if (!title.ok) fieldErrors.title = title.message;

  const customerLabel = text(raw.customerLabel, 'Customer label', LIMITS.customerLabel);
  if (!customerLabel.ok) fieldErrors.customerLabel = customerLabel.message;

  const promisedDate = typeof raw.promisedDate === 'string' ? raw.promisedDate.trim() : '';
  if (!promisedDate) fieldErrors.promisedDate = 'Promised date is required.';
  else if (!isDateOnly(promisedDate)) fieldErrors.promisedDate = 'Use a valid date (YYYY-MM-DD).';

  const sourceUrl = typeof raw.sourceUrl === 'string' ? raw.sourceUrl.trim() : '';
  if (!sourceUrl) fieldErrors.sourceUrl = 'Source URL is required.';
  else if (!parseSameSiteUrl(sourceUrl, siteBaseUrl)) {
    fieldErrors.sourceUrl = `Use an https link on this Atlassian site (${new URL(siteBaseUrl).hostname}).`;
  }

  const excerpt = text(raw.evidenceExcerpt, 'Recorded excerpt', LIMITS.evidenceExcerpt, true);
  if (!excerpt.ok) fieldErrors.evidenceExcerpt = excerpt.message;

  const ids = raw.linkedIssueIds;
  let linkedIssueIds: string[] = [];
  if (!Array.isArray(ids) || ids.length < LIMITS.linkedIssues.min) {
    fieldErrors.linkedIssueIds = 'Link at least one Jira issue.';
  } else if (ids.length > LIMITS.linkedIssues.max) {
    fieldErrors.linkedIssueIds = `Link at most ${LIMITS.linkedIssues.max} Jira issues.`;
  } else if (!ids.every(isIssueId)) {
    fieldErrors.linkedIssueIds = 'One of the linked issues is not a valid Jira issue.';
  } else if (new Set(ids).size !== ids.length) {
    fieldErrors.linkedIssueIds = 'Each Jira issue can be linked only once.';
  } else {
    linkedIssueIds = [...ids];
  }

  if (Object.keys(fieldErrors).length > 0 || !title.ok || !customerLabel.ok || !excerpt.ok) {
    return { ok: false, fieldErrors, message: 'Check the highlighted fields.' };
  }
  return {
    ok: true,
    value: {
      title: title.value,
      customerLabel: customerLabel.value,
      promisedDate,
      sourceUrl,
      evidenceExcerpt: excerpt.value,
      linkedIssueIds,
    },
  };
}

/** Validate `{ id }`-style payloads. Commitment ids are UUIDs generated by the app. */
export function validateCommitmentId(raw: unknown): string | null {
  if (!isRecord(raw) || typeof raw.id !== 'string') return null;
  return /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/.test(raw.id) ? raw.id : null;
}

/** Explicit confirmation flag required by fulfil/archive/create mitigation. */
export function isConfirmed(raw: unknown): boolean {
  return isRecord(raw) && raw.confirm === true;
}

export function validateCreateMitigationInput(raw: unknown): Validation<CreateMitigationInput> {
  if (!isRecord(raw)) return { ok: false, fieldErrors: {}, message: 'The mitigation details are missing.' };
  const commitmentId = validateCommitmentId({ id: raw.commitmentId });
  if (!commitmentId) return { ok: false, fieldErrors: {}, message: 'Unknown commitment.' };
  if (raw.confirm !== true) {
    return { ok: false, fieldErrors: {}, message: 'Creating a Jira issue needs explicit confirmation.' };
  }
  const summary = text(raw.summary, 'Summary', LIMITS.mitigationSummary);
  if (!summary.ok) return { ok: false, fieldErrors: {}, message: summary.message };
  const description = text(raw.description, 'Description', LIMITS.mitigationDescription, true);
  if (!description.ok) return { ok: false, fieldErrors: {}, message: description.message };
  return {
    ok: true,
    value: {
      commitmentId,
      summary: summary.value,
      description: description.value,
      confirm: true,
      acknowledgePendingReview: raw.acknowledgePendingReview === true,
    },
  };
}
